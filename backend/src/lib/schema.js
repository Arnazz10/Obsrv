import { withConnection } from './db.js';

const TABLES = {
  ALERT_SIGNALS: `
    CREATE TABLE alert_signals (
      alert_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
      alert_key    VARCHAR2(400) NOT NULL,
      alert_type   VARCHAR2(20)  NOT NULL,
      severity     CHAR(1)       NOT NULL,
      service_name VARCHAR2(150),
      region_name  VARCHAR2(100),
      title        VARCHAR2(400) NOT NULL,
      detail       VARCHAR2(2000),
      log_id       NUMBER,
      occurrences  NUMBER DEFAULT 1 NOT NULL,
      status       VARCHAR2(12) DEFAULT 'OPEN' NOT NULL,
      created_at   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
      updated_at   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT uq_alert_signals_key UNIQUE (alert_key),
      CONSTRAINT chk_alert_signals_status CHECK (status IN ('OPEN', 'ACKED', 'RESOLVED'))
    )`,
  NOTIFICATIONS: `
    CREATE TABLE notifications (
      notification_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
      alert_id        NUMBER,
      audience        VARCHAR2(10)  NOT NULL,
      severity        CHAR(1)       NOT NULL,
      title           VARCHAR2(400) NOT NULL,
      message         VARCHAR2(4000) NOT NULL,
      source          VARCHAR2(10)  DEFAULT 'MANUAL' NOT NULL,
      channels        VARCHAR2(100) DEFAULT 'in-app' NOT NULL,
      created_at      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT chk_notifications_audience CHECK (audience IN ('USERS', 'DBA', 'BOTH')),
      CONSTRAINT chk_notifications_source CHECK (source IN ('AUTO', 'MANUAL'))
    )`
};

/** Creates the alert/notification tables on databases that were set up before they existed. */
export async function ensureSchema() {
  await withConnection(async (connection) => {
    const existing = await connection.execute('SELECT table_name FROM user_tables WHERE table_name IN (:a, :b)', { a: 'ALERT_SIGNALS', b: 'NOTIFICATIONS' });
    const have = new Set(existing.rows.map((r) => r.TABLE_NAME));
    for (const [name, ddl] of Object.entries(TABLES)) {
      if (!have.has(name)) {
        await connection.execute(ddl);
        console.log(`Created table ${name}`);
      }
    }
  });
}
