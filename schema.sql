CREATE SEQUENCE log_id_seq START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE alert_id_seq START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;

CREATE TABLE regions (
  region_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  region_name VARCHAR2(100) NOT NULL UNIQUE,
  region_tz   VARCHAR2(100) NOT NULL
);

CREATE TABLE services (
  service_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  service_name VARCHAR2(150) NOT NULL,
  region_id    NUMBER NOT NULL,
  CONSTRAINT uq_services_name_region UNIQUE (service_name, region_id),
  CONSTRAINT fk_services_region FOREIGN KEY (region_id) REFERENCES regions(region_id)
);

CREATE TABLE users (
  user_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  user_name VARCHAR2(150) NOT NULL UNIQUE,
  role      VARCHAR2(20) NOT NULL,
  CONSTRAINT chk_users_role CHECK (role IN ('admin', 'analyst', 'viewer'))
);

CREATE TABLE logs (
  log_id      NUMBER DEFAULT log_id_seq.NEXTVAL PRIMARY KEY,
  service_id  NUMBER NOT NULL,
  region_id   NUMBER NOT NULL,
  log_time    TIMESTAMP WITH TIME ZONE NOT NULL,
  severity    CHAR(1) NOT NULL,
  payload     JSON NOT NULL,
  embedding   VECTOR(768, FLOAT32) NOT NULL,
  CONSTRAINT fk_logs_service FOREIGN KEY (service_id) REFERENCES services(service_id),
  CONSTRAINT fk_logs_region FOREIGN KEY (region_id) REFERENCES regions(region_id),
  CONSTRAINT chk_logs_severity CHECK (severity IN ('I', 'W', 'E', 'C'))
);

CREATE TABLE alerts (
  alert_id    NUMBER DEFAULT alert_id_seq.NEXTVAL PRIMARY KEY,
  log_id      NUMBER NOT NULL,
  alert_type  VARCHAR2(100) NOT NULL,
  created_at  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  resolved    BOOLEAN DEFAULT FALSE NOT NULL,
  CONSTRAINT fk_alerts_log FOREIGN KEY (log_id) REFERENCES logs(log_id)
);

CREATE INDEX idx_logs_log_time ON logs (log_time);
CREATE INDEX idx_logs_service_id ON logs (service_id);
CREATE INDEX idx_logs_severity ON logs (severity);

CREATE MATERIALIZED VIEW LOG ON logs
  WITH ROWID, SEQUENCE (service_id, log_time, severity)
  INCLUDING NEW VALUES;

CREATE OR REPLACE VIEW v_critical_errors AS
SELECT
  l.log_id,
  l.service_id,
  s.service_name,
  l.region_id,
  r.region_name,
  r.region_tz,
  l.log_time AT TIME ZONE r.region_tz AS local_log_time,
  l.severity,
  JSON_VALUE(l.payload, '$.message' RETURNING VARCHAR2(4000)) AS message,
  l.payload,
  l.embedding
FROM logs l
JOIN services s ON s.service_id = l.service_id
JOIN regions r ON r.region_id = l.region_id
WHERE l.severity IN ('C', 'E');

CREATE MATERIALIZED VIEW mv_hourly_errors
BUILD IMMEDIATE
REFRESH FAST ON COMMIT
ENABLE QUERY REWRITE
AS
SELECT
  l.service_id,
  TRUNC(CAST(l.log_time AT TIME ZONE 'UTC' AS TIMESTAMP), 'HH') AS hour_start_utc,
  COUNT(*) AS error_count
FROM logs l
WHERE l.severity IN ('E', 'C')
GROUP BY l.service_id, TRUNC(CAST(l.log_time AT TIME ZONE 'UTC' AS TIMESTAMP), 'HH');

